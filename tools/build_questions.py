#!/usr/bin/env python3
"""Builds questions.js from questions/*.json and checks every question.

Each JSON file is an array of {id, topic, q, a, d: [3 distractors], why, src}. Edit those files,
run `python3 tools/build_questions.py`, then bump VERSION in sw.js so iPads pick up the change.
Question ids must stay stable: progress on the iPad is stored by id.
"""
import glob, hashlib, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOPICS = [
    # Oral Exam Guide
    ('docs', 'Documents & Airworthiness', 'oeg', '#4a4f57'),
    ('pilot', 'Pilot Requirements & ADM', 'oeg', '#4a4f57'),
    ('perf', 'Performance & Limitations', 'oeg', '#d9730d'),
    ('wb', 'Weight & Balance', 'oeg', '#d9730d'),
    ('controls', 'Flight Controls & Flaps', 'oeg', '#0f7f8a'),
    ('engine', 'Engines & Propellers', 'oeg', '#0f7f8a'),
    ('gear', 'Landing Gear', 'oeg', '#0f7f8a'),
    ('fuel', 'Fuel, Oil & Hydraulics', 'oeg', '#0f7f8a'),
    ('elec', 'Electrical & Avionics', 'oeg', '#0f7f8a'),
    ('instr', 'Pitot-Static & Gyros', 'oeg', '#0f7f8a'),
    ('env', 'Heat, Ice, Oxygen & Pressurization', 'oeg', '#0f7f8a'),
    ('aero', 'Aerodynamics & Vmc', 'oeg', '#c62828'),
    ('eo', 'Engine-Out Procedures', 'oeg', '#c62828'),
    ('acs', 'Maneuvers & ACS Standards', 'oeg', '#6b3fc7'),
    # PA-34-200 Seneca I
    ('s-speeds', 'Speeds & Limitations', 'seneca', '#d9730d'),
    ('s-wb', 'Weight & Balance', 'seneca', '#d9730d'),
    ('s-perf', 'Performance Charts', 'seneca', '#d9730d'),
    ('s-engine', 'Engines & Propellers', 'seneca', '#138a4a'),
    ('s-fuel', 'Fuel System', 'seneca', '#138a4a'),
    ('s-gear', 'Landing Gear & Brakes', 'seneca', '#138a4a'),
    ('s-elec', 'Electrical, Vacuum & Instruments', 'seneca', '#138a4a'),
    ('s-airframe', 'Airframe, Controls, Heat & Ice', 'seneca', '#138a4a'),
    ('s-normal', 'Normal Procedures', 'seneca', '#1e5bd8'),
    ('s-emerg', 'Emergency Procedures', 'seneca', '#c62828'),
]
# Files are read in this order so Study mode follows the book.
ORDER = ["o1", "o2", "o3", "o4", "o5", "o6", "o7", "o8", "f1", "f2", "f3", "f4", "p1", "p5", "p2", "p4", "r4", "p3"]


def main():
    keys = {t[0] for t in TOPICS}
    files = sorted(glob.glob(os.path.join(ROOT, 'questions', '*.json')),
                   key=lambda f: (ORDER.index(os.path.basename(f)[:-5]) if os.path.basename(f)[:-5] in ORDER else 99, f))
    out, seen, errors = [], set(), []
    for f in files:
        for x in json.load(open(f)):
            where = f"{os.path.basename(f)} {x.get('id')}"
            if x.get('drop'):
                continue
            for k in ('id', 'topic', 'q', 'a', 'd', 'why', 'src'):
                if not x.get(k):
                    errors.append(f'{where}: missing {k}')
            if x.get('topic') not in keys:
                errors.append(f"{where}: unknown topic {x.get('topic')}")
            if not isinstance(x.get('d'), list) or len(x['d']) != 3:
                errors.append(f'{where}: needs exactly 3 distractors')
            elif len({c.strip().lower() for c in [x['a']] + x['d']}) != 4:
                errors.append(f'{where}: duplicate choices')
            if x.get('id') in seen:
                errors.append(f'{where}: duplicate id')
            seen.add(x.get('id'))
            out.append({'id': x['id'], 't': x['topic'], 'q': x['q'].strip(), 'a': x['a'].strip(),
                        'd': [c.strip() for c in x['d']], 'why': x['why'].strip(), 'src': x['src'].strip()})
    if errors:
        print('\n'.join(errors)); sys.exit(1)
    used = {q['t'] for q in out}
    topics = [{'key': k, 'title': t, 'group': g, 'color': c} for k, t, g, c in TOPICS if k in used]
    body = json.dumps(out, ensure_ascii=False, separators=(',', ':'))
    ver = hashlib.sha1(body.encode()).hexdigest()[:7]
    with open(os.path.join(ROOT, 'questions.js'), 'w') as fh:
        fh.write('// Generated by tools/build_questions.py from questions/*.json. Do not edit by hand.\n')
        fh.write(f"const QBANK_VERSION = '{ver}';\n")
        fh.write('const TOPICS = ' + json.dumps(topics, ensure_ascii=False, indent=1) + ';\n')
        fh.write('const QUESTIONS = [\n' + ',\n'.join(json.dumps(q, ensure_ascii=False) for q in out) + '\n];\n')
    counts = {}
    for q in out:
        counts[q['t']] = counts.get(q['t'], 0) + 1
    print(f'{len(out)} questions, bank {ver}')
    for k, t, g, c in TOPICS:
        print(f'  {g:7} {k:11} {counts.get(k, 0):4}')


if __name__ == '__main__':
    main()
